import random
a = sorted(random.sample(range(0, 1000000), 100))  # список для поиска: 100 чисел от 0 до 200
b = 67  # будем его искать
c = len(a)  # длина списка
d = 0  # счётчик сравнений для линейного поиска
e = -1  #чтоб когда первый элемент искомый не писало мол не не найдено
print("начальный список: ", a)
print("ЛИНЕЙНЫЙ ПОИСК:")
for i in range(c):
    d += 1  # засчитывание счётчика для линейного поиска
    if b == a[i]:  # сравнивает искомый элемент с элементом списка
        e = i  # если значения совпали, e принимает значение его индекса
        break
if e != -1:  # эта проверка нужна только для корректного вывода
    print("индекс элемента: ", e)
    print("количество сравнений: ", d)
else:
    print("число не найдено")
print("БИНАРНЫЙ ПОИСК: ")
f = 0  # нижняя граница поиска
g = len(a) - 1  # верхняя граница поиска
h = 0  # счётчик сравнений (бинарный поиск)
j = -1  # индекс найденного элемента (-1 = не найден)
while f <= g:  # пока границы не пересеклись
    h += 1  # +1 сравнение
    k = (f + g) // 2  # середина текущего диапазона
    if a[k] == b:  # сравнение с искомым элементом
        j = k  # запоминаем индекс совпадения
        break  # дальше искать не нужно
    elif a[k] < b:  # середина меньше искомого
        f = k + 1  # сдвигаем нижнюю границу вправо
    else:  # середина больше искомого
        g = k - 1  # сдвигаем верхнюю границу влево
if j == -1:  # вывод результата
    print("число не найдено")
else:
    print("индекс элемента: ", j)
    print("количество сравнений: ", h)
